#!/usr/bin/env python3
"""Build index.html — a single-file Kindle-style reader for everything in library/.

Usage:  python3 tools/build-reader.py [--serve [port]]

No configuration needed. The script discovers content from the folder structure
(Next.js-style routing):

    library/
      <section>/            first-level folder  = a shelf section in the library
        section.json        optional: {"title": "..."}
        <book>/             second-level folder = one book
          book.json         optional: {"title", "author", "description",
                                       "cover": "cover.jpg" (relative) or a data: URL,
                                       "lang": "en",
                                       "podcast": true  → public audio feed, see
                                                          tools/podcast/podcast.mjs}
          01-intro.md       .md files, sorted by filename = chapters
          <part>/           deeper folders = named parts; their .md files are
                            chapters grouped under a part heading in the TOC
          images/           folders with no .md inside are ignored (assets)
        loose-note.md       a loose .md directly in a section = a one-chapter book

Ordering: natural sort of file/folder names. A leading "NN-" numeric prefix
controls order and is stripped from display titles. Chapter titles come from
the first "# H1" line of the file (code fences are ignored), falling back to the
prettified filename.

Images: `![alt](relative/path.png)` inside a chapter is rewritten to a
repo-relative path at build time, so it renders when the repo root is served
(GitHub Pages, --serve). http(s)/data: URLs are left as they are.

Re-run any time you add or edit markdown files. Output: index.html (repo root)
plus sw.js and manifest.webmanifest (the offline/installable PWA companions).
"""
import base64
import hashlib
import json
import os
import re
import sys
import time

TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS)
LIBRARY = os.path.join(ROOT, "library")
OUT = os.path.join(ROOT, "index.html")
SW_OUT = os.path.join(ROOT, "sw.js")
MANIFEST_OUT = os.path.join(ROOT, "manifest.webmanifest")

# Bump this when the service worker's *logic* changes so old workers' caches are
# discarded. Content updates do not need a bump: the worker re-validates the
# page on every visit and tells the open page when a newer build has landed.
OFFLINE_CACHE = "library-offline-v6"
SHARE_INBOX_CACHE = "library-share-inbox"

# The service worker.
#  * The page itself (index.html, which embeds the whole library) is served
#    stale-while-revalidate: the cached copy opens instantly, even on a slow
#    phone connection, while a fresh copy is fetched in the background. If the
#    fresh copy differs, every open tab gets a {type:"updated"} message and the
#    reader shows a "tap to reload" toast.
#  * Other same-origin files (sw.js, manifest, images referenced by chapters)
#    are network-first with a cache fallback.
#  * POST to ./share is the Web Share Target (Android Chrome: "Share → Library"
#    an .epub from any app): the files are parked in a cache and the page is
#    opened with ?shared=1, where the in-browser importer picks them up.
#  * The page is served cross-origin isolated (COOP + COEP added here, since
#    GitHub Pages can't send headers). That unlocks SharedArrayBuffer, which
#    the Kokoro voices (Listen) need to run on several threads — about twice
#    as fast as the single thread a non-isolated page is limited to.
#  * Studio audio (audio/<book>/*.m4a + .json, made by tools/narrate/narrate.py)
#    is cache-first and stays for offline listening. Phones ask for audio in
#    byte ranges; a range request is answered from the cached whole file, and
#    the page fetches each chapter whole once so a copy is there to slice.
#  * Only runs over http(s) — a no-op on file://.
SERVICE_WORKER = """\
/* Auto-generated by tools/build-reader.py — do not edit by hand. */
const CACHE = "%(cache)s";
const INBOX = "%(inbox)s";
const PAGE_KEY = "./index.html";
const CORE = ["./", "./index.html", "./manifest.webmanifest"];

self.addEventListener("install", e => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    await Promise.allSettled(CORE.map(u => c.add(new Request(u, {cache: "reload"}))));
    self.skipWaiting();
  })());
});

self.addEventListener("activate", e => {
  e.waitUntil((async () => {
    const keys = await caches.keys();
    // only our own old versions: other caches (transformers-cache holds the
    // ~90 MB Kokoro voice model) belong to libraries the page uses
    await Promise.all(keys.filter(k => k.startsWith("library-") && k !== CACHE && k !== INBOX)
      .map(k => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener("message", e => {
  if (e.data && e.data.type === "skipWaiting") self.skipWaiting();
});

function sameDoc(a, b) {
  // Is the fresh response the same build as the cached one? Compare validators
  // that static hosts send (GitHub Pages: ETag; python http.server: Last-Modified).
  for (const h of ["etag", "last-modified", "content-length"]) {
    const x = a.headers.get(h), y = b.headers.get(h);
    if (x && y) return x === y;
  }
  return true; // nothing to compare — don't nag
}

function isolated(res) {
  if (!res || res.status === 0 || res.type === "opaqueredirect") return res;
  const h = new Headers(res.headers);
  h.set("Cross-Origin-Opener-Policy", "same-origin");
  h.set("Cross-Origin-Embedder-Policy", "require-corp");
  return new Response(res.body, {status: res.status, statusText: res.statusText, headers: h});
}

async function notifyClients(msg) {
  const list = await self.clients.matchAll({type: "window", includeUncontrolled: true});
  list.forEach(c => c.postMessage(msg));
}

async function handleShare(req) {
  try {
    const form = await req.formData();
    const files = form.getAll("file").filter(f => f && typeof f.arrayBuffer === "function");
    const inbox = await caches.open(INBOX);
    let n = 0;
    for (const f of files) {
      const headers = {"Content-Type": f.type || "application/octet-stream",
                       "X-File-Name": encodeURIComponent(f.name || ("shared-" + n))};
      await inbox.put("./shared/" + Date.now() + "-" + (n++), new Response(f, {headers}));
    }
  } catch (err) { /* fall through — the page shows an error if the inbox is empty */ }
  return Response.redirect("./?shared=1", 303);
}

async function serveAudio(req, cache) {
  const range = req.headers.get("range");
  const key = new Request(req.url);            // the whole file, however it was asked for
  let full = await cache.match(key);
  if (!full) {
    let fresh = null;
    if (!range) {
      try { fresh = await fetch(req); } catch (err) { return Response.error(); }
      if (fresh && fresh.status === 200) cache.put(key, fresh.clone());
      return fresh;
    }
    // a range request for a file not cached yet: let the network answer it,
    // and quietly fetch the whole file for next time
    try { fresh = await fetch(req); } catch (err) { return Response.error(); }
    fetch(key).then(r => { if (r && r.status === 200) cache.put(key, r); }).catch(() => {});
    return fresh;
  }
  if (!range) return full;
  const buf = await full.arrayBuffer();
  const m = /bytes=(\\d*)-(\\d*)/.exec(range);
  let start = m && m[1] ? parseInt(m[1], 10) : 0;
  let end = m && m[2] ? parseInt(m[2], 10) : buf.byteLength - 1;
  if (m && !m[1] && m[2]) { start = Math.max(0, buf.byteLength - parseInt(m[2], 10)); end = buf.byteLength - 1; }
  end = Math.min(end, buf.byteLength - 1);
  if (start > end) return new Response(null, {status: 416, headers: {"Content-Range": "bytes */" + buf.byteLength}});
  const h = new Headers(full.headers);
  h.set("Content-Range", `bytes ${start}-${end}/${buf.byteLength}`);
  h.set("Content-Length", String(end - start + 1));
  h.set("Accept-Ranges", "bytes");
  return new Response(buf.slice(start, end + 1), {status: 206, statusText: "Partial Content", headers: h});
}

self.addEventListener("fetch", e => {
  const req = e.request;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;         // never touch third parties
  if (req.method === "POST" && url.pathname.endsWith("/share")) {
    e.respondWith(handleShare(req));
    return;
  }
  if (req.method !== "GET") return;

  const isPage = req.mode === "navigate" || /\\/(index\\.html)?$/.test(url.pathname);
  const isAudio = /\\/audio\\/[^/]+\\/[^/]+\\.(m4a|json)$/.test(url.pathname);
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    if (isAudio) return serveAudio(req, cache);
    if (isPage) {
      const cached = await cache.match(PAGE_KEY);
      const refresh = fetch(req).then(async fresh => {
        if (fresh && fresh.ok) {
          const changed = cached ? !sameDoc(fresh, cached) : false;
          await cache.put(PAGE_KEY, fresh.clone());
          if (changed) notifyClients({type: "updated"});
        }
        return fresh;
      }).catch(() => null);
      if (cached) { e.waitUntil(refresh); return isolated(cached); }
      const fresh = await refresh;
      return fresh ? isolated(fresh) : Response.error();
    }
    try {
      const fresh = await fetch(req);
      if (fresh && fresh.ok) cache.put(req, fresh.clone());
      return fresh;
    } catch (err) {
      const cached = await cache.match(req, {ignoreSearch: true});
      return cached || Response.error();
    }
  })());
});
""" % {"cache": OFFLINE_CACHE, "inbox": SHARE_INBOX_CACHE}

# An open-book glyph, drawn as an SVG so no binary asset is needed.
