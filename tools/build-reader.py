def natural_key(name):
    """'10-foo' sorts after '2-bar': split digit runs and compare numerically."""
    return [int(p) if p.isdigit() else p.lower() for p in re.split(r"(\d+)", name)]


def prettify(name):
    """Folder/file name -> display title: strip 'NN-' prefix, dashes -> spaces, Title Case."""
    name = re.sub(r"^\d+[-_. ]+", "", name)
    words = re.split(r"[-_]+", name)
    return " ".join(w[:1].upper() + w[1:] for w in words if w)


FENCE_RE = re.compile(r"^\s*(`{3,}|~{3,})")


def body_lines(md):
    """Lines of `md` that are outside ``` / ~~~ code fences."""
    fence, out = None, []
    for ln in md.splitlines():
        if fence:
            if ln.strip().startswith(fence):
                fence = None
            continue
        m = FENCE_RE.match(ln)
        if m:
            fence = m.group(1)[:3]
            continue
        out.append(ln)
    return out


def title_of(md, fallback):
    for line in body_lines(md):
        m = re.match(r"#\s+(.*)", line)
        if m:
            return m.group(1).strip()
    return fallback


def word_count(md):
    return len(re.findall(r"\S+", md))


WARNINGS = []


def warn(msg):
    WARNINGS.append(msg)
    print(f"  ! {msg}")


IMG_RE = re.compile(r"(!\[[^\]]*\]\()([^)\s]+)(\s*(?:\"[^\"]*\")?\))")


def rewrite_images(md, chapter_dir_rel):
    """Make relative image paths repo-relative so they resolve from index.html.

    Returns (md, missing) where missing lists referenced files that don't exist.
    Fenced code is left untouched.
    """
    missing = []

    def fix(m):
        src = m.group(2)
        if re.match(r"^(https?:|data:|/)", src, re.I):
            return m.group(0)
        rel = os.path.normpath(os.path.join(chapter_dir_rel, src)).replace(os.sep, "/")
        if not os.path.isfile(os.path.join(ROOT, rel)):
            missing.append(src)
        return m.group(1) + rel + m.group(3)

    out, fence = [], None
    for ln in md.splitlines(keepends=True):
        if fence:
            out.append(ln)
            if ln.strip().startswith(fence):
                fence = None
            continue
        fm = FENCE_RE.match(ln)
        if fm:
            fence = fm.group(1)[:3]
            out.append(ln)
            continue
        out.append(IMG_RE.sub(fix, ln))
    return "".join(out), missing


def lint_chapter(relpath, md, missing_images=()):
    """Warn about content the reader can't display well."""
    body = "\n".join(body_lines(md))
    if not re.search(r"^#\s+\S", body, re.M):
        warn(f"{relpath}: no '# Title' H1 — TOC will show the prettified filename")
    for src in missing_images:
        warn(f"{relpath}: image not found: {src}")
    if re.search(r"^ {4,}([-*+]|\d+[.)])\s", body, re.M):
        warn(f"{relpath}: list nested deeper than one level — deeper levels render flattened")


def lint_prefixes(dirpath, names):
    """Two '03-...' entries in one folder sort by the rest of the name — usually a mistake."""
    seen = {}
    for name in names:
        m = re.match(r"^(\d+)[-_. ]", name)
        if not m:
            continue
        key = int(m.group(1))
        if key in seen:
            rel = os.path.relpath(dirpath, ROOT)
            warn(f"{rel}: duplicate numeric prefix {m.group(1)!r} on {seen[key]!r} and {name!r}")
        else:
            seen[key] = name


def read_json(path):
    if os.path.isfile(path):
        with open(path, encoding="utf-8") as fh:
            try:
                return json.load(fh)
            except ValueError as e:
                warn(f"{os.path.relpath(path, ROOT)}: invalid JSON ({e}) — ignored")
    return {}


def list_entries(dirpath):
    """(files, dirs) — visible entries, natural-sorted."""
    files, dirs = [], []
    for name in sorted(os.listdir(dirpath), key=natural_key):
        if name.startswith("."):
            continue
        full = os.path.join(dirpath, name)
        (dirs if os.path.isdir(full) else files).append(name)
    return files, dirs


def has_markdown(dirpath):
    for _, _, files in os.walk(dirpath):
        if any(f.endswith(".md") and not f.startswith(".") for f in files):
            return True
    return False


def read_chapter(full):
    """-> (md with repo-relative image paths, missing image list)."""
    with open(full, encoding="utf-8") as fh:
        md = fh.read()
    md = md.lstrip("\ufeff").replace("\r\n", "\n")
    chapter_dir_rel = os.path.relpath(os.path.dirname(full), ROOT)
    return rewrite_images(md, chapter_dir_rel)


def collect_book_chapters(book_dir, book_id, chapters):
    """Walk a book folder; append chapter dicts to `chapters`, return their indices.

    Files and subfolders at each level are processed in one natural-sorted pass,
    so a '05-part-two/' folder can be ordered between chapter files. Nested
    folders become part labels ('Categories', 'Part Two / Basics', ...).
    Folders with no markdown anywhere inside (images/, assets/) are skipped.
    """
    indices = []

    def walk(dirpath, part_label):
        entries = sorted(os.listdir(dirpath), key=natural_key)
        lint_prefixes(dirpath, [e for e in entries if not e.startswith(".")])
        for name in entries:
            if name.startswith("."):
                continue
            full = os.path.join(dirpath, name)
            if os.path.isdir(full):
                if not has_markdown(full):
                    continue
                sub = prettify(name)
                walk(full, f"{part_label} / {sub}" if part_label else sub)
            elif name.endswith(".md"):
                md, missing = read_chapter(full)
                rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
                lint_chapter(rel, md, missing)
                indices.append(len(chapters))
                chapters.append({
                    "id": rel,
                    "file": name,
                    "book": book_id,
                    "part": part_label,
                    "num": len(indices),
                    "title": title_of(md, prettify(os.path.splitext(name)[0])),
                    "words": word_count(md),
                    "md": md,
                })

    walk(book_dir, "")
    return indices


def cover_of(meta, book_dir):
    """book.json "cover": a data: URL is passed through; a relative file path is
    made repo-relative (and checked). Anything else is dropped with a warning."""
    cover = (meta.get("cover") or "").strip()
    if not cover:
        return ""
    if cover.startswith("data:") or re.match(r"^https?:", cover, re.I):
        return cover
    rel = os.path.normpath(os.path.join(os.path.relpath(book_dir, ROOT), cover)).replace(os.sep, "/")
    if not os.path.isfile(os.path.join(ROOT, rel)):
        warn(f"{os.path.relpath(book_dir, ROOT)}/book.json: cover file not found: {cover}")
        return ""
    return rel


ACCESS_CONFIG = os.path.join(TOOLS, "access-config.json")


def load_access_token():
    """Optional site-lock token, checked in order:
    1. SITE_ACCESS_TOKEN env var (how CI supplies it, from a repo secret —
       keeps the token out of the public repo entirely).
    2. tools/access-config.json ({"token": "..."}) for local builds — gitignored.
    Absent both = gating disabled, site is fully open (the default).

    Only a SHA-256 of the token is embedded in index.html, so the key can't be
    read out of the page source. (The *content* is still in the page — this is
    a privacy curtain for a personal library, not access control.)"""
    env_token = (os.environ.get("SITE_ACCESS_TOKEN") or "").strip()
    if env_token:
        return env_token
    if not os.path.isfile(ACCESS_CONFIG):
        return None
    with open(ACCESS_CONFIG, encoding="utf-8") as fh:
        return (json.load(fh).get("token") or "").strip() or None


def embed(obj):
    """JSON safe to place inside <script> — `<` can never form `</script>` or
    `<!--`, which the HTML tokenizer treats specially even in JSON blocks."""
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")


def build():
    if not os.path.isdir(LIBRARY):
        sys.exit(f"No library/ folder found at {LIBRARY} — nothing to build.")

    sections = []
    chapters = []  # flat, global list; books reference chapters by index

    sec_files, sec_dirs = list_entries(LIBRARY)
    for stray in sec_files:
        if stray.endswith(".md"):
            print(f"  ! ignoring {stray} at library/ root — put .md files inside a section folder")

    for sec_name in sec_dirs:
        sec_dir = os.path.join(LIBRARY, sec_name)
        sec_meta = read_json(os.path.join(sec_dir, "section.json"))
        section = {"id": sec_name, "title": sec_meta.get("title", prettify(sec_name)), "books": []}

        files, dirs = list_entries(sec_dir)

        # loose .md files directly in a section: each becomes a one-chapter book
        for fname in files:
            if not fname.endswith(".md"):
                continue
            full = os.path.join(sec_dir, fname)
            md, missing = read_chapter(full)
            rel = f"library/{sec_name}/{fname}"
            lint_chapter(rel, md, missing)
            stem = os.path.splitext(fname)[0]
            book_id = f"{sec_name}/{stem}"
            title = title_of(md, prettify(stem))
            idx = len(chapters)
            chapters.append({
                "id": rel, "file": fname, "book": book_id, "part": "", "num": 1,
                "title": title, "words": word_count(md), "md": md,
            })
            section["books"].append({
                "id": book_id, "title": title, "author": "", "description": "",
                "chapters": [idx],
            })

        # folders in a section: each is a book
        for book_name in dirs:
            book_dir = os.path.join(sec_dir, book_name)
            meta = read_json(os.path.join(book_dir, "book.json"))
            book_id = f"{sec_name}/{book_name}"
            ch_idx = collect_book_chapters(book_dir, book_id, chapters)
            if not ch_idx:
                print(f"  ! skipping empty book folder library/{sec_name}/{book_name}")
                continue
            book = {
                "id": book_id,
                "title": meta.get("title", prettify(book_name)),
                "author": meta.get("author", ""),
                "description": meta.get("description", ""),
                "chapters": ch_idx,
            }
            cover = cover_of(meta, book_dir)
            if cover:
                book["cover"] = cover
            if meta.get("lang"):
                book["lang"] = meta["lang"]
            # a public podcast feed made by tools/podcast/podcast.mjs ("podcast": true)
            feed = f"podcast/{book_id.replace('/', '-')}/feed.xml"
            if os.path.exists(os.path.join(ROOT, feed)):
                book["podcast"] = feed
            section["books"].append(book)

        if section["books"]:
            sections.append(section)

    # Studio audio made on the Mac by tools/narrate/narrate.py: chapter id ->
    # {u: audio url, m: timing-map url, d: seconds, l: voice label}
    narrated = {}
    audio_dir = os.path.join(ROOT, "audio")
    if os.path.isdir(audio_dir):
        for slug in sorted(os.listdir(audio_dir)):
            idx = read_json(os.path.join(audio_dir, slug, "index.json"))
            for e in (idx or {}).get("chapters", []):
                if os.path.exists(os.path.join(audio_dir, slug, e["file"])):
                    narrated[e["id"]] = {"u": f"audio/{slug}/{e['file']}", "m": f"audio/{slug}/{e['map']}",
                                         "d": e["dur"], "l": e.get("label", "Studio")}
    if narrated:
        hours = sum(v["d"] for v in narrated.values()) / 3600
        print(f"Studio audio: {len(narrated)} chapters, {hours:.1f} h (audio/)")

    with open(os.path.join(TOOLS, "reader-template.html"), encoding="utf-8") as fh:
        tpl = fh.read()

    token = load_access_token()
    token_hash = hashlib.sha256(token.encode("utf-8")).hexdigest() if token else None
    build_id = time.strftime("%Y%m%d-%H%M%S")

    html = (tpl.replace("__LIB_DATA__", embed(sections))
               .replace("__CHAPTER_DATA__", embed(chapters))
               .replace("__ACCESS_HASH__", embed(token_hash))
               .replace("__NARRATED__", embed(narrated))
               .replace("__OFFLINE_CACHE__", OFFLINE_CACHE)
               .replace("__SHARE_INBOX__", SHARE_INBOX_CACHE)
               .replace("__BUILD_ID__", build_id))
    for leftover in ("__LIB_DATA__", "__CHAPTER_DATA__", "__ACCESS_HASH__", "__NARRATED__",
                     "__OFFLINE_CACHE__", "__SHARE_INBOX__", "__BUILD_ID__"):
        if leftover in html:
            sys.exit(f"template placeholder {leftover} was not replaced — template/build mismatch")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(html)

    # PWA companions: the service worker (offline caching, share target) + web
    # app manifest (installable "Add to Home Screen", share/file handlers).
    with open(SW_OUT, "w", encoding="utf-8") as fh:
        fh.write(SERVICE_WORKER)

    icon = "data:image/svg+xml;base64," + base64.b64encode(_ICON_SVG.encode("utf-8")).decode("ascii")
    manifest = {
        "name": "Library",
        "short_name": "Library",
        "description": "A personal Kindle-style reading library.",
        "start_url": "./",
        "scope": "./",
        "display": "standalone",
        "background_color": "#fbfaf7",
        "theme_color": "#fbfaf7",
        "icons": [
            {"src": icon, "sizes": "512x512", "type": "image/svg+xml", "purpose": "any"},
            {"src": icon, "sizes": "192x192", "type": "image/svg+xml", "purpose": "maskable"},
        ],
        # Android Chrome / desktop Chromium: "Share → Library" an .epub / .md
        # file from any app. (Not supported by iOS Safari — there the in-app
        # "Import" button opens the Files picker instead.)
        "share_target": {
            "action": "./share",
            "method": "POST",
            "enctype": "multipart/form-data",
            "params": {"title": "title", "text": "text", "url": "url",
                       "files": [{"name": "file",
                                  "accept": ["application/epub+zip", ".epub",
                                             "text/markdown", ".md", "text/plain", ".txt"]}]},
        },
        # Desktop Chromium: double-clicking an .epub opens it in the installed app.
        "file_handlers": [
            {"action": "./", "accept": {"application/epub+zip": [".epub"],
                                        "text/markdown": [".md", ".markdown"],
                                        "text/plain": [".txt"]}},
        ],
    }
    with open(MANIFEST_OUT, "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, ensure_ascii=False, indent=2)

    n_books = sum(len(s["books"]) for s in sections)
    size_kb = len(html.encode("utf-8")) // 1024
    print(f"Wrote {OUT}: {len(sections)} sections, {n_books} books, "
          f"{len(chapters)} chapters, {size_kb} KB  (build {build_id})")
    print(f"Wrote {SW_OUT} and {MANIFEST_OUT} (offline PWA, cache {OFFLINE_CACHE})")
    if token:
        print("Site lock is ON — the bare URL shows a lock screen; only links containing "
              "?k=<token> (or a browser that already unlocked it) get in. Only the token's "
              "SHA-256 is in index.html.")
    if size_kb > 8 * 1024:
        warn(f"index.html is {size_kb // 1024} MB — page load/parse will start to feel it; "
             "consider splitting rarely-read sections into a second library")
